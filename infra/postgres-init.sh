#!/bin/sh
set -eu
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v ON_ERROR_STOP=1 -v app_password="$AEGIS_APP_DB_PASSWORD" -v demo_password="$AEGIS_DEMO_DB_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE aegis_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD %L', :'app_password') \gexec
SELECT format('CREATE ROLE aegis_demo LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD %L', :'demo_password') \gexec
CREATE DATABASE aegis_demo OWNER aegis_demo;
REVOKE CONNECT ON DATABASE aegis FROM PUBLIC;
GRANT CONNECT ON DATABASE aegis TO aegis_app;
REVOKE CONNECT ON DATABASE aegis_demo FROM PUBLIC;
GRANT CONNECT ON DATABASE aegis_demo TO aegis_demo;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SQL
